# 1. تحميل الحزم الأساسية
library(mirt)
library(mirtCAT)
library(shiny)

# -------------------------------------------------------------
# 2. إنشاء بنك فقرات بمعالم جاهزة (10 فقرات بنموذج 2PL)
# -------------------------------------------------------------
# معاملات التمييز (Slopes / a)
a_params <- c(1.2, 1.5, 0.9, 1.8, 1.1, 1.4, 1.0, 1.6, 1.3, 1.7)

# معاملات السهولة/الاعتراض (Intercepts / d حيث d = -a * b)
# لنفترض صعوبات متدرجة من b = -2 إلى b = +2
b_params <- seq(-2, 2, length.out = 10)
d_params <- -a_params * b_params

# دمج المعالم وإنشاء كائن mirt جاهز دون الحاجة لبيانات استجابة أولية
pars <- data.frame(a1 = a_params, d = d_params)
item_bank <- generate.mirt_object(parameters = pars, itemtype = '2PL')

# -------------------------------------------------------------
# 3. إعداد إطار بيانات الأسئلة والخيارات (df)
# -------------------------------------------------------------
df <- data.frame(
  Question = c(
    "1. ما هو ناتج العملية الحسابية: 15 + 27؟",
    "2. إذا كان س + 5 = 12، فما قيمة س؟",
    "3. ما هو الجذر التربيعي للعدد 144؟",
    "4. مساحة مربع طول ضلعه 6 سم تساوي:",
    "5. ناتج ضرب 0.5 في 40 يساوي:",
    "6. ما هو العدد الأولي من بين الأعداد التالية؟",
    "7. ما قيمة س في المعادلة: 2س - 4 = 10؟",
    "8. النسبة المئوية للعدد 25 من 200 هي:",
    "9. محيط مستطيل بعداه 4 سم و 6 سم يساوي:",
    "10. ما هو الكسر المكافئ لـ 0.75؟"
  ),
  Option.1 = c("32", "5", "10", "24 سم²", "10", "9", "5", "10%", "10 سم", "1/2"),
  Option.2 = c("42", "7", "12", "36 سم²", "20", "15", "7", "12.5%", "20 سم", "3/4"),
  Option.3 = c("40", "8", "14", "12 سم²", "25", "21", "8", "15%", "24 سم", "2/3"),
  Option.4 = c("45", "6", "16", "30 سم²", "15", "17", "6", "25%", "12 سم", "4/5"),
  Type = "radio",
  stringsAsFactors = FALSE
)

# مفتاح الإجابات الصحيحة للأسئلة (رقم الخيار الصحيح)
# الإجابات الصحيحة وفق الترتيب: 2, 2, 2, 2, 2, 4, 2, 2, 2, 2
key <- c(2, 2, 2, 2, 2, 4, 2, 2, 2, 2)

# إضافة عمود الإجابة الصحيحة Answer إلى df (شرط أساسي في mirtCAT عند تمرير mo لحساب الدرجات)
# نربط نص الخيار المطابق لرقم الخيار في key
df$Answer <- sapply(1:nrow(df), function(i) df[i, paste0("Option.", key[i])])

# -------------------------------------------------------------
# 4. ضبط محددات التصميم التكيفي (Adaptive Design)
# -------------------------------------------------------------
design_settings <- list(
  min_items = 4,         # أقل عدد يقدم للمفحوص
  max_items = 8,         # الحد الأقصى للفقرات
  min_SEM = 0.40,        # التوقف عند وصول الخطأ المعياري للقدرة لأقل من 0.40
  thetas.start = 0       # افتراض البداية بقدرة متوسطة
)

# -------------------------------------------------------------
# 5. تشغيل الاختبار التكيفي
# -------------------------------------------------------------
# عند تنفيذ هذا السطر، ستفتح نافذة Shiny تفاعلية
cat_session <- mirtCAT(
  df = df,
  mo = item_bank,
  criteria = 'MI',          # اختيار الفقرة ذات أقصى معلومة لفيشر
  method = 'EAP',           # تقدير القدرة عبر Expected A Posteriori
  start_item = 'MI',        # اختيار أول فقرة تعطي أعلى معلومة عند قدرة صفر
  design = design_settings,
  shinyGUI = list(
    title = "اختبار مهارات الرياضيات التكيفي",
    firstpage = list(
      shiny::h2("مرحباً بك في الاختبار التكيفي"),
      shiny::p("هذا الاختبار يتكيف تلقائياً مع مستوى إجاباتك. اضغط 'التالي' للبدء.")
    ),
    demographics = list(
      shiny::textInput(
        inputId = "participant_name",
        label = "اسم المشارك",
        value = ""
      ),
      shiny::selectInput(
        inputId = "education_level",
        label = "المستوى الدراسي",
        choices = c("", "مبتدئ", "متوسط", "متقدم"),
        selected = ""
      )
    ),
    demographics_inputIDs = c("participant_name", "education_level"),
    lastpage = function(person) {
      th <- extract.mirtCAT(person, "thetas")
      se <- extract.mirtCAT(person, "thetas_SE")
      list(
        shiny::h3("تم إنهاء الاختبار بنجاح"),
        shiny::p("شكراً لمشاركتك في هذا الاختبار التكيفي."),
        shiny::p(sprintf("القدرة المقدرة (Theta): %.2f", th[1])),
        shiny::p(sprintf("الخطأ المعياري للقياس (SE): %.2f", se[1]))
      )
    }
  )
)
